const coreEnglishToKey = Object.fromEntries(
  Object.entries(en).map(([key, value]) => [value, key]),
) as Record<string, TranslationKey>;
const coreVietnameseToKey = Object.fromEntries(
  Object.entries(vi).map(([key, value]) => [value, key]),
) as Record<string, TranslationKey>;
const vietnamesePhraseToEnglish = Object.fromEntries(
  Object.entries(viUiPhrases).map(([englishPhrase, vietnamesePhrase]) => [
    vietnamesePhrase,
    englishPhrase,
  ]),
) as Record<string, string>;

function translateKnownPhrase(locale: Locale, phrase: string): string {
  const coreKey = coreEnglishToKey[phrase] ?? coreVietnameseToKey[phrase];
  if (coreKey) {
    return locale === "vi" ? vi[coreKey] : en[coreKey];
  }

  if (locale === "vi") {
    return viUiPhrases[phrase] ?? phrase;
  }

  return vietnamesePhraseToEnglish[phrase] ?? phrase;
}

