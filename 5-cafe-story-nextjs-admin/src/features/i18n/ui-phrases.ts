export type UiPhrase = keyof typeof viUiPhrases;
export type UiTranslate = (
  phrase: UiPhrase,
  values?: TranslationValues,
) => string;
export type UiTextTranslate = (
  phrase: string,
  values?: TranslationValues,
) => string;

const viCorePhrases = Object.fromEntries(
  (Object.keys(en) as Array<keyof typeof en>).map((key) => [en[key], vi[key]]),
) as Record<string, string>;

export function createUiTranslator(locale: "en" | "vi"): UiTranslate {
  return (phrase, values) =>
    interpolate(locale === "vi" ? viUiPhrases[phrase] : phrase, values);
}

export function useUiTranslate(): UiTranslate {
  const { locale } = useI18n();
  return useMemo(() => createUiTranslator(locale), [locale]);
}

export function createUiTextTranslator(locale: "en" | "vi"): UiTextTranslate {
  return (phrase, values) => {
    const template =
      locale === "vi"
        ? (viUiPhrases as Record<string, string>)[phrase] ??
          viCorePhrases[phrase] ??
          phrase
        : phrase;
    return interpolate(template, values);
  };
}

export function useUiText(): UiTextTranslate {
  const { locale } = useI18n();
  return useMemo(() => createUiTextTranslator(locale), [locale]);
}
