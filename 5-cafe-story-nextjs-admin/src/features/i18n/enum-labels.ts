export function translateEnumLabel(locale: Locale, value: unknown): string {
  if (typeof value === "boolean") {
    return locale === "vi"
      ? value
        ? "Hoạt động"
        : "Không hoạt động"
      : value
        ? "Active"
        : "Inactive";
  }
  const raw = value === null || value === undefined ? "UNKNOWN" : String(value);
  const normalized = raw.toUpperCase();
  const labels = locale === "vi" ? VI_ENUM_LABELS : EN_ENUM_LABELS;
  return labels[normalized] ?? raw.replaceAll("_", " ");
}

export function useEnumLabel() {
  const { locale } = useI18n();
  return useCallback((value: unknown) => translateEnumLabel(locale, value), [locale]);
}
